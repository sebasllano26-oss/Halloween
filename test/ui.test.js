function page({ origin = 'https://halloween.example', local = false, demo = false, url = '/', animated = false } = {}) {
  const errors = [], console = new VirtualConsole();
  console.on('jsdomError', error => { if (!/navigation|window.scrollTo/.test(error.message)) errors.push(error.message); });
  const html = readFileSync(resolve(demo ? 'dist/demo/index.html' : 'dist/index.html'), 'utf8');
  const dom = new JSDOM(local ? html.replace('data-runtime="vercel"', 'data-runtime="local"') : html, { url: origin + url, runScripts: 'outside-only', pretendToBeVisual: animated, virtualConsole: console });
  const w = dom.window;
  w.matchMedia = query => ({ matches: animated ? query.includes('no-preference') : query.includes(': reduce'), media: query, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {} });
  w.scrollTo = () => {}; w.HTMLElement.prototype.scrollIntoView = () => {};
  w.HTMLDialogElement.prototype.showModal = function () { this.open = true; }; w.HTMLDialogElement.prototype.close = function () { this.open = false; };
  w.HTMLMediaElement.prototype.play = async function () {};
  w.HTMLMediaElement.prototype.pause = function () {};
  Object.defineProperty(w, 'crypto', { value: { getRandomValues: array => webcrypto.getRandomValues(array) } });
  w.AbortSignal = {}; w.AbortController = AbortController;
  const $ = selector => w.document.querySelector(selector);
  const waitFor = async (check, message = 'No se completó la operación') => { const limit = Date.now() + 5000; while (!check()) { if (Date.now() > limit) throw new Error(message + '\n' + w.document.body.textContent.slice(-1800)); await new Promise(resolve => setTimeout(resolve, 15)); } };
  const submit = () => $('#survey-form').dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true }));
  const answer = (id, index = 0) => { const input = w.document.querySelectorAll('input[name="' + id + '"]')[index]; input.checked = true; input.dispatchEvent(new w.Event('change', { bubbles: true })); };
  const boot = () => w.eval(readFileSync(resolve(demo ? 'dist/demo/assets/app.js' : 'dist/assets/app.js'), 'utf8'));
  return { dom, w, $, waitFor, submit, answer, boot, errors };
}

